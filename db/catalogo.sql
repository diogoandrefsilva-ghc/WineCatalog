-- =====================================================================
-- WineCatalog — O CATÁLOGO DE VINHOS (schema `winecatalog`)
--
-- FONTE DE VERDADE. Este ficheiro é a única definição do catálogo que
-- existe em lado nenhum. Esteve até setembro de 2026 num schema à parte
-- (`catalogo`) e num terceiro repo (Garrafeira), e mudou-se para aqui —
-- ver `db/migracao-catalogo-para-winecatalog.sql` para o porquê e para o
-- como.
--
-- O QUE ISTO É: a memória do que já se sabe sobre um vinho — o que a IA
-- já procurou (nas apps todas), e o que alguém já confirmou por ter a
-- garrafa em casa. Existe por uma razão só: cada chamada à IA custa
-- dinheiro, e a ficha de um vinho não muda de semana para semana. Se
-- alguém já procurou "Quinta do Crasto Reserva 2019" na WineSelection,
-- a Garrafeira não tem de a procurar outra vez — e vice-versa.
--
-- O QUE ISTO NÃO É: não guarda uma linha do que é de alguém. Aqui entra
-- só o que é FACTO SOBRE O VINHO (a referência: castas, região, nota do
-- Vivino, preço médio de mercado) — nunca o que é da GARRAFA ou da
-- PESSOA: quanto se pagou, onde está arrumada, as notas escritas à mão, a
-- fotografia tirada em casa. É a mesma linha que a Garrafeira já traça
-- entre "vinho" e "garrafa", e é ela que torna este catálogo partilhável
-- sem partilhar garrafeira nenhuma.
--
-- QUEM LHE TOCA, e por onde:
--   · a WineCatalog (esta app) — pelas funções de leitura e de decisão
--     lá em baixo, com o JWT de uma pessoa;
--   · a `vinho-info` (Garrafeira) e a `sugerir-vinho`/`verificar-vinhos`
--     (WineSelection) — por RPC com a service role, e só pelas três:
--     `juntar`, `procurar`, `procurar_lote`;
--   · o trigger `garrafeira.vinhos_catalogo` — esse vive no repo
--     Garrafeira (pendura-se em `garrafeira.vinhos`, que é dela) e chama
--     `winecatalog.juntar`.
--
-- Correr DEPOIS de `db/schema.sql` (precisa da `winecatalog.allowed_users`
-- para saber quem pode ler). É IDEMPOTENTE.
--
-- Quase todos os comentários abaixo vêm do ficheiro original e ficam
-- como estavam: foram pagos com erros, e um erro que já se cometeu é a
-- coisa mais barata que este ficheiro tem.
-- =====================================================================

-- A service_role não tem acesso a schemas fora de `public` só por ser
-- service_role — BYPASSRLS é sobre policies, não sobre GRANTs. Sem isto,
-- as três Edge Functions falham com 42501 e sem uma palavra do lado de
-- quem chama. (Mesma nota que já está no `wineselection/db/schema.sql`.)






-- ---------------------------------------------------------------------
-- A tabela
--
-- A ficha é um `jsonb` e não vinte colunas de propósito: quem a lê e quem
-- a escreve são Edge Functions que já trabalham em JSON, e a JUNÇÃO (ver
-- `winecatalog.juntar`) percorre os campos um a um — com colunas, essa função
-- eram vinte atribuições escritas à mão que alguém se esquecia de
-- acrescentar no dia em que aparecesse um campo novo.
--
-- `origens` é a proveniência CAMPO A CAMPO: {campo: {o:origem, f:força,
-- em:quando}}. É o que permite juntar duas leituras sem uma apagar a
-- outra às cegas — uma pesquisa a sério não deve ser substituída por uma
-- extração mais fraca, e nada deve substituir o que alguém confirmou por
-- ter a garrafa na mão.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS winecatalog.vinhos (
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  -- DUAS identidades por linha, e é preciso que sejam duas: ver
  -- `winecatalog.achar()`. `chave` é o nome MAIS o produtor; `chave_nome` é só
  -- o nome, como vem escrito numa carta de restaurante.
  chave         text NOT NULL,          -- nome+produtor+ano ("crasto-reserva|2019")
  chave_base    text NOT NULL,          -- o mesmo sem o ano
  chave_nome    text,                   -- só o nome+ano; NULL quando o nome
                                        -- sozinho não distingue nada
  base_nome     text,                   -- o mesmo sem o ano
  nome          text NOT NULL DEFAULT '',
  produtor      text NOT NULL DEFAULT '',
  ano           integer,
  ficha         jsonb NOT NULL DEFAULT '{}'::jsonb,   -- os factos do vinho
  origens       jsonb NOT NULL DEFAULT '{}'::jsonb,   -- proveniência campo a campo
  fontes        jsonb NOT NULL DEFAULT '[]'::jsonb,   -- [{titulo,url}], no máximo 8
  vezes         integer NOT NULL DEFAULT 0,           -- quantas vezes foi escrito (diagnóstico)
  visto_em      timestamptz NOT NULL DEFAULT now(),   -- última vez que serviu uma pergunta
  criado_em     timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT vinhos_pkey PRIMARY KEY (id),
  CONSTRAINT vinhos_chave_uniq UNIQUE (chave)
);

CREATE INDEX IF NOT EXISTS vinhos_chave_base_idx ON winecatalog.vinhos (chave_base);
CREATE INDEX IF NOT EXISTS vinhos_chave_nome_idx ON winecatalog.vinhos (chave_nome);
CREATE INDEX IF NOT EXISTS vinhos_base_nome_idx  ON winecatalog.vinhos (base_nome);
CREATE INDEX IF NOT EXISTS vinhos_visto_idx      ON winecatalog.vinhos (visto_em DESC);

-- RLS ligada e SEM UMA ÚNICA POLICY, de propósito: isto tranca a tabela a
-- toda a gente menos à service_role (que passa por cima da RLS). Não há
-- GRANT nenhum a `anon`/`authenticated` — nem de leitura. Quem alimenta o
-- catálogo do lado do browser é o trigger da Garrafeira, e esse é
-- SECURITY DEFINER: escreve sem que a pessoa tenha de poder escrever aqui.
--
-- Porquê tão fechado, se o que está cá dentro não é de ninguém: a LISTA de
-- vinhos que passaram por aqui diz alguma coisa sobre o que as pessoas têm
-- em casa, mesmo que cada linha à parte não diga. Uma leitura por nome
-- (que é tudo o que as apps precisam) não é a mesma coisa que poder ler a
-- lista toda, e é só a primeira que se abre — pela Edge Function.
ALTER TABLE winecatalog.vinhos ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------
-- AS DUAS TABELAS DA DECISÃO HUMANA
--
-- Nascem aqui em cima, e não lá para o fim ao pé das funções que as usam,
-- por uma razão de mecânica: a `winecatalog.achar()` passou a resolver
-- aliases, e uma função `LANGUAGE sql` é validada quando se CRIA. A pôr
-- estas tabelas depois dela, o ficheiro não corre.
--
-- `alias`: "estas duas linhas são o mesmo vinho". A linha perdedora NÃO
-- se apaga e NÃO se lhe tocam as chaves — fica como está, e é a `achar`
-- que passa a responder com a linha-alvo quando esbarra nela. Desfazer é
-- literalmente apagar uma linha desta tabela.
--
-- `distintos`: "estas duas NÃO são o mesmo". Sem isto, a lista de
-- candidatos volta a propor o mesmo par todas as semanas — e uma lista
-- que insiste em erros deixa de se ler, que é o caminho para alguém
-- carregar em "são o mesmo" sem olhar e juntar um Vallado a um Esporão.
-- O par guarda-se sempre ordenado (a < b) para que marcar (A,B) e marcar
-- (B,A) sejam a mesma linha.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS winecatalog.alias (
  chave_de       text NOT NULL,          -- a chave da linha que deixou de responder
  chave_para     text NOT NULL,
  id_de          bigint NOT NULL,
  id_para        bigint NOT NULL,
  nome_de        text,
  ano_de         integer,
  -- {campo: {antes, antes_origem, depois_origem}} — o estado ANTERIOR de
  -- cada campo que a fusão mexeu, para desfazer ser exato e não um palpite
  campos_movidos jsonb NOT NULL DEFAULT '{}'::jsonb,
  quem           text,
  quando         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT alias_pkey PRIMARY KEY (chave_de)
);
CREATE INDEX IF NOT EXISTS alias_para_idx ON winecatalog.alias (id_para);
CREATE INDEX IF NOT EXISTS alias_de_idx   ON winecatalog.alias (id_de);

CREATE TABLE IF NOT EXISTS winecatalog.distintos (
  chave_a text NOT NULL,
  chave_b text NOT NULL,
  quem    text,
  quando  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT distintos_pkey PRIMARY KEY (chave_a, chave_b),
  CONSTRAINT distintos_ordem_chk CHECK (chave_a < chave_b)
);


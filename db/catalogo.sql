-- 2. UM CAMINHO DE LEITURA PARA A UI
--
-- Até aqui `winecatalog.vinhos` tinha RLS com ZERO policies: nem o
-- `authenticated` lia uma linha, e não havia um único ecrã em lado nenhum
-- que mostrasse o que lá está. Só as Edge Functions (service_role) lhe
-- chegavam.
--
-- Duas saídas, e a escolhida é a segunda:
--   · policies de SELECT — mais simples, mas abre a tabela a QUALQUER
--     pessoa com login em QUALQUER app do projeto que aponte para o
--     schema `winecatalog`, e o schema está EXPOSTO na API. A lista de
--     vinhos que passaram por aqui diz alguma coisa sobre o que as
--     pessoas têm em casa, mesmo que cada linha à parte não diga;
--   · funções SECURITY DEFINER com `REVOKE` e `GRANT` só a quem deve —
--     a mesma razão que levou ao REVOKE da `juntar`/`procurar`/
--     `procurar_lote`, e a mesma disciplina.
--
-- Cada função nova nasce com EXECUTE para PUBLIC. Os REVOKEs estão todos
-- juntos no FIM deste ficheiro, e confirmam-se com a consulta que está lá.
-- =====================================================================

-- ---------------------------------------------------------------------
-- O preço como número, ou NULL. A ficha é jsonb e um dia tem lá "34,90"
-- escrito à mão: um cast directo rebentava a lista inteira por causa de
-- uma linha.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION winecatalog.preco_num(f jsonb)
  RETURNS numeric LANGUAGE sql IMMUTABLE
  SET search_path TO 'winecatalog', 'public'
AS $$
  SELECT CASE WHEN jsonb_typeof(f -> 'preco_medio') = 'number'
              THEN (f ->> 'preco_medio')::numeric END;
$$;

-- As faixas de preço vivem AQUI e não no browser: são o que a `listar`
-- conta e o que ela filtra, e duas listas destas divergem no dia em que
-- alguém mexe numa só.
CREATE OR REPLACE FUNCTION winecatalog.faixa_preco(p numeric)
  RETURNS text LANGUAGE sql IMMUTABLE
  SET search_path TO 'winecatalog', 'public'
AS $$
  SELECT CASE
           WHEN p IS NULL THEN NULL
           WHEN p <  15 THEN '<15'
           WHEN p <  30 THEN '15-30'
           WHEN p <  60 THEN '30-60'
           ELSE '60+'
         END;
$$;

-- Uma linha do catálogo como a UI a quer numa LISTA: sem a ficha inteira
-- (são ~19 campos por linha e a lista tem centenas), mas com o que
-- responde à pergunta "vale a pena abrir esta?".
CREATE OR REPLACE FUNCTION winecatalog.resumo_linha(r winecatalog.vinhos)
  RETURNS jsonb LANGUAGE sql STABLE
  SET search_path TO 'winecatalog', 'public'
AS $$
  SELECT jsonb_build_object(
    'id',       r.id,
    'chave',    r.chave,
    'nome',     r.nome,
    'produtor', r.produtor,
    'ano',      r.ano,
    'tipo',     r.ficha ->> 'tipo',
    'regiao',   COALESCE(r.ficha ->> 'regiao', r.ficha ->> 'pais'),
    'castas',   r.ficha -> 'castas',
    'nota',     r.ficha -> 'vivino_nota',
    'preco',    r.ficha -> 'preco_medio',
    -- A fotografia do vinho (a do RÓTULO, que é do vinho — nunca a
    -- `imagem_path` tirada em casa, que apanha a prateleira à volta e é
    -- de quem a tem). A lista desenha a garrafa quando isto vem vazio,
    -- por isso é seguro estar em falta — o que não pode é obrigar o ecrã
    -- a abrir a ficha inteira só para saber se existe.
    'imagem',   r.ficha ->> 'imagem_url',
    'campos',   (SELECT count(*) FROM jsonb_object_keys(r.ficha)),
    -- A força MÁXIMA que esta linha tem em cima: é o que distingue um
    -- vinho que alguém pesquisou a sério de um que foi escrito à pressa
    -- numa garrafeira e nunca mais ninguém tocou.
    'forca',    (SELECT COALESCE(max((o.value ->> 'f')::integer), 0)
                   FROM jsonb_each(r.origens) o),
    'fontes',   jsonb_array_length(COALESCE(r.fontes, '[]'::jsonb)),
    'vezes',    r.vezes,
    'vistoEm',      r.visto_em,
    'atualizadoEm', r.atualizado_em
  );
$$;

-- A LISTA, com procura e FILTROS. `p_procura` vazio e sem filtro nenhum
-- devolve tudo (por ordem da última vez que serviu uma pergunta — que é a
-- ordem por que alguém quer ver isto, não a alfabética).
--
-- A procura bate em quatro sítios porque é por esses quatro que se procura
-- um vinho: o nome, o produtor, a região e a casta. Os dois primeiros
-- passam também pela CHAVE (`winecatalog.tokens`), e é isso que faz "qta do
-- crasto" encontrar a linha escrita "Quinta do Crasto" e "crasto"
-- encontrar as duas — a mesma normalização que o catálogo já usa para
-- decidir o que é o mesmo vinho, sem uma segunda ideia sobre acentos.
--
-- Os quatro filtros (tipo, região, castas, faixa de preço) são do SQL e
-- não do browser porque a lista é PAGINADA (50 de cada vez): filtrar do
-- lado do cliente filtrava só a página que por acaso já tinha vindo —
-- "3 tintos do Douro" quando havia trinta.
--
-- E as CONTAGENS por opção (`facetas`) voltam no mesmo pedido, contadas
-- com os OUTROS grupos aplicados mas não o próprio: é o que faz
-- "Branco 7" continuar visível depois de se escolher Tinto. Um grupo que
-- só conta o que já está filtrado por ele mesmo mostra sempre o total
-- escolhido, e não serve para nada.
--
-- As CASTAS, e só elas, aceitam as duas leituras: escolher Touriga
-- Nacional e Syrah pode ser "qualquer uma das duas" (`p_castas_todas`
-- false, o costume) ou "os lotes que levam as duas" (true). Um vinho tem
-- UM tipo e UMA região — ali a pergunta não se põe, e é por isso que o
-- visto no ecrã só aparece nas castas.
--
-- A assinatura mudou (quatro parâmetros novos, e depois o quinto), por
-- isso as antigas têm de sair — senão ficavam todas e o PostgREST
-- escolhia a que lhe desse jeito.
DROP FUNCTION IF EXISTS winecatalog.listar(text, integer, integer);
DROP FUNCTION IF EXISTS winecatalog.listar(text, integer, integer,
                                           text[], text[], text[], text[]);

CREATE OR REPLACE FUNCTION winecatalog.listar(
  p_procura text    DEFAULT NULL,
  p_limite  integer DEFAULT 50,
  p_saltar  integer DEFAULT 0,
  p_tipos   text[]  DEFAULT NULL,
  p_regioes text[]  DEFAULT NULL,
  p_castas  text[]  DEFAULT NULL,
  p_precos  text[]  DEFAULT NULL,  -- ids das faixas: '<15','15-30','30-60','60+'
  p_castas_todas boolean DEFAULT false
) RETURNS jsonb
  LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE
  v_q    text    := lower(trim(COALESCE(p_procura, '')));
  v_toks text[]  := CASE WHEN v_q = '' THEN ARRAY[]::text[] ELSE winecatalog.tokens(v_q) END;
  v_lim  integer := LEAST(GREATEST(COALESCE(p_limite, 50), 1), 200);
  v_off  integer := GREATEST(COALESCE(p_saltar, 0), 0);
  v_e    boolean := COALESCE(p_castas_todas, false);
  v_res  jsonb;
BEGIN
  IF NOT winecatalog.pode_ler() THEN
    RAISE EXCEPTION 'Sem acesso ao catálogo.';
  END IF;

  -- Uma CTE e não uma tabela temporária: uma função STABLE não pode
  -- escrever, nem sequer num `CREATE TEMP TABLE`, e o Postgres só o diz
  -- quando a função CORRE. É a mesma pedra em que já se tropeçou do outro
  -- lado (um `UPDATE` do `visto_em` dentro de algo marcado STABLE) e que
  -- está escrita no CLAUDE.md — aqui não se repete.
  --
  -- E a linha inteira viaja numa COLUNA (`linha winecatalog.vinhos`), não
  -- como `v.*` espalhado pelas CTEs. A razão é o `resumo_linha`, que
  -- recebe uma `winecatalog.vinhos`: assim que uma CTE acrescenta uma
  -- coluna sua (aqui os quatro `ok_*`), o `p.*` dessa CTE passa a ser um
  -- `record` com colunas a mais e o Postgres recusa-o com
  -- «cannot cast type record to vinhos» — em tempo de EXECUÇÃO, com a
  -- lista inteira a morrer por causa disso. Uma coluna de tipo composto
  -- não tem esse problema: é sempre uma `vinhos`, leve o resto da CTE o
  -- que levar.
  WITH achados AS (
    -- As castas normalizadas uma vez só (`[]` quando a ficha não tem lista
    -- nenhuma): a seguir são precisas três vezes — no filtro, na contagem
    -- e na contagem cruzada do modo "todas".
    SELECT v.id, v.visto_em, v.ficha, v AS linha,
           CASE WHEN jsonb_typeof(v.ficha -> 'castas') = 'array'
                THEN v.ficha -> 'castas' ELSE '[]'::jsonb END AS cas
      FROM winecatalog.vinhos v
     WHERE
       -- Uma linha já fundida noutra não entra na lista: deixou de
       -- responder por si (a `achar` desvia-a) e passou a ser o rasto de
       -- uma decisão. Quem a quer ver abre a ficha da alvo, onde ela
       -- aparece, e é lá que se desfaz.
       NOT EXISTS (SELECT 1 FROM winecatalog.alias a WHERE a.id_de = v.id)
       AND (
         v_q = ''
         OR v.nome     ILIKE '%' || v_q || '%'
         OR v.produtor ILIKE '%' || v_q || '%'
         OR COALESCE(v.ficha ->> 'regiao', '')     ILIKE '%' || v_q || '%'
         OR COALESCE(v.ficha ->> 'sub_regiao', '') ILIKE '%' || v_q || '%'
         OR EXISTS (
              SELECT 1 FROM jsonb_array_elements_text(
                             CASE WHEN jsonb_typeof(v.ficha -> 'castas') = 'array'
                                  THEN v.ficha -> 'castas' ELSE '[]'::jsonb END) c
               WHERE c ILIKE '%' || v_q || '%')
         -- e pela CHAVE: todos os tokens escritos têm de estar na linha
         OR (cardinality(v_toks) > 0
             AND string_to_array(v.chave_base, '-') @> v_toks)
       )
  ),
  -- Cada linha sabe quais dos quatro filtros passa. É isto que permite
  -- contar um grupo "como se ele não estivesse escolhido" sem repetir a
  -- procura quatro vezes.
  marcados AS (
    SELECT a.*,
      (p_tipos IS NULL OR cardinality(p_tipos) = 0
        OR (a.ficha ->> 'tipo') = ANY(p_tipos))                                   AS ok_tipo,
      (p_regioes IS NULL OR cardinality(p_regioes) = 0
        OR COALESCE(a.ficha ->> 'regiao', a.ficha ->> 'pais') = ANY(p_regioes))   AS ok_regiao,
      -- `?|` = tem alguma; `?&` = tem todas. Em jsonb os dois operadores
      -- olham para os ELEMENTOS de um array de texto, que é exatamente o
      -- que a `ficha -> 'castas'` é.
      (p_castas IS NULL OR cardinality(p_castas) = 0
        OR (CASE WHEN v_e THEN a.cas ?& p_castas ELSE a.cas ?| p_castas END))     AS ok_casta,
      (p_precos IS NULL OR cardinality(p_precos) = 0
        OR winecatalog.faixa_preco(winecatalog.preco_num(a.ficha)) = ANY(p_precos)) AS ok_preco
      FROM achados a
  ),
  filtrados AS (
    SELECT * FROM marcados WHERE ok_tipo AND ok_regiao AND ok_casta AND ok_preco
  ),
  pagina AS (
    SELECT f.linha, f.visto_em, f.id FROM filtrados f
     ORDER BY f.visto_em DESC, f.id DESC
     OFFSET v_off LIMIT v_lim
  ),
  f_tipo AS (
    SELECT m.ficha ->> 'tipo' AS v, count(*) AS n
      FROM marcados m
     WHERE m.ok_regiao AND m.ok_casta AND m.ok_preco AND m.ficha ->> 'tipo' IS NOT NULL
     GROUP BY 1
  ),
  f_regiao AS (
    SELECT COALESCE(m.ficha ->> 'regiao', m.ficha ->> 'pais') AS v, count(*) AS n
      FROM marcados m
     WHERE m.ok_tipo AND m.ok_casta AND m.ok_preco
       AND COALESCE(m.ficha ->> 'regiao', m.ficha ->> 'pais') IS NOT NULL
     GROUP BY 1
  ),
  f_casta AS (
    SELECT c AS v, count(*) AS n
      FROM marcados m,
           LATERAL jsonb_array_elements_text(m.cas) c
     WHERE m.ok_tipo AND m.ok_regiao AND m.ok_preco
       -- Em "qualquer uma" a regra do costume basta: o grupo não se conta
       -- a si próprio, e por isso "Syrah 28" continua lá depois de se
       -- escolher Touriga Nacional.
       --
       -- Em "todas em simultâneo" ignorar o grupo inteiro dava um número
       -- que não é o de lado nenhum: "Syrah 28" com a lista a mostrar
       -- três vinhos. Aqui a mesma ideia aplica-se à OPÇÃO e não ao
       -- grupo — conta-se com as OUTRAS castas escolhidas por cima, mas
       -- nunca com a própria. Uma que já esteja escolhida mostra o total
       -- do cruzamento (e continua visível, que é o que permite
       -- desmarcá-la); uma que não esteja mostra em quantos se ficaria se
       -- fosse acrescentada — e desaparece quando esse número é zero,
       -- que é a resposta certa para um caminho sem saída.
       AND (NOT v_e OR p_castas IS NULL OR cardinality(p_castas) = 0
            OR m.cas ?& (SELECT COALESCE(array_agg(s), ARRAY[]::text[])
                           FROM unnest(p_castas) s WHERE s <> c))
     GROUP BY 1
  ),
  f_preco AS (
    SELECT winecatalog.faixa_preco(winecatalog.preco_num(m.ficha)) AS v, count(*) AS n
      FROM marcados m
     WHERE m.ok_tipo AND m.ok_regiao AND m.ok_casta
       AND winecatalog.faixa_preco(winecatalog.preco_num(m.ficha)) IS NOT NULL
     GROUP BY 1
  )
  SELECT jsonb_build_object(
           'total',  (SELECT count(*) FROM filtrados),
           'linhas', COALESCE((SELECT jsonb_agg(winecatalog.resumo_linha(p.linha)
                                        ORDER BY p.visto_em DESC, p.id DESC)
                                 FROM pagina p), '[]'::jsonb),
           'facetas', jsonb_build_object(
             -- Região e castas são listas abertas: mostram-se as mais
             -- cheias, e o ecrã acrescenta as que já estão escolhidas
             -- (senão não havia como as desmarcar).
             'tipos',   COALESCE((SELECT jsonb_agg(x) FROM (
                          SELECT jsonb_build_object('v', v, 'n', n) AS x
                            FROM f_tipo ORDER BY n DESC, v) s), '[]'::jsonb),
             'regioes', COALESCE((SELECT jsonb_agg(x) FROM (
                          SELECT jsonb_build_object('v', v, 'n', n) AS x
                            FROM f_regiao ORDER BY n DESC, v LIMIT 12) s), '[]'::jsonb),
             'castas',  COALESCE((SELECT jsonb_agg(x) FROM (
                          SELECT jsonb_build_object('v', v, 'n', n) AS x
                            FROM f_casta ORDER BY n DESC, v LIMIT 12) s), '[]'::jsonb),
             'precos',  COALESCE((SELECT jsonb_agg(x) FROM (
                          SELECT jsonb_build_object('v', v, 'n', n) AS x
                            FROM f_preco ORDER BY v) s), '[]'::jsonb)
           )
         )
    INTO v_res;

  RETURN v_res;
END;
$$;

-- UMA linha, inteira, com a proveniência CAMPO A CAMPO.
--
-- É o ponto do ecrã do §4.2 e a razão de a app existir: `origens` guarda
-- {campo: {o:origem, f:força, em:quando}} desde o primeiro dia e nunca
-- ninguém o viu. Sem isto não há como responder à pergunta que decide se
-- se confia num número — "de onde é que isto veio?".
--
-- Devolve também as linhas que foram FUNDIDAS nesta (`aliases`): quem abre
-- uma ficha tem direito a saber que ela é o resultado de uma decisão de
-- alguém, e a desfazê-la.
CREATE OR REPLACE FUNCTION winecatalog.ver(p_id bigint)
  RETURNS jsonb
  LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE
  r winecatalog.vinhos%ROWTYPE;
BEGIN
  IF NOT winecatalog.pode_ler() THEN
    RAISE EXCEPTION 'Sem acesso ao catálogo.';
  END IF;
  SELECT * INTO r FROM winecatalog.vinhos v WHERE v.id = p_id;
  IF r.id IS NULL THEN RETURN NULL; END IF;

  RETURN winecatalog.resumo_linha(r) || jsonb_build_object(
    'chaveBase', r.chave_base,
    'chaveNome', r.chave_nome,
    'baseNome',  r.base_nome,
    'ficha',     r.ficha,
    'origens',   r.origens,
    'fontes',    COALESCE(r.fontes, '[]'::jsonb),
    'criadoEm',  r.criado_em,
    'aliases',   COALESCE((
        SELECT jsonb_agg(jsonb_build_object(
                 'chaveDe', a.chave_de, 'nome', a.nome_de, 'ano', a.ano_de,
                 'quem', a.quem, 'quando', a.quando,
                 'campos', (SELECT count(*) FROM jsonb_object_keys(a.campos_movidos))
               ) ORDER BY a.quando DESC)
          FROM winecatalog.alias a WHERE a.id_para = r.id), '[]'::jsonb)
  );
END;
$$;





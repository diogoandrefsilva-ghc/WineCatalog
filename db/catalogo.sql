-- ---------------------------------------------------------------------
-- GENÉRICO: as palavras que NÃO identificam um vinho
--
-- Serve só à lista de candidatos, e é o que a fez passar de 28 pares para
-- 7 na base real. Sem ela, a varredura propunha coisas destas:
--
--   HERDADE DO SOBROSO Grande Reserva  ×  Bafarela Grande Reserva
--   Esporão Touriga Nacional           ×  Quinta do Noval Touriga Nacional
--   Leo d'Honor                        ×  Ermelinda Freitas Syrah
--
-- Três ruídos diferentes, e vale a pena saber distingui-los:
--   · QUALIFICADORES ("grande", "reserva", "garrafeira", "velhas") — dizem
--     a gama, não o vinho. Dois vinhos que só partilham isto não têm nada
--     a ver um com o outro;
--   · CASTAS ("touriga", "nacional", "syrah") — é a uva, e metade do Douro
--     engarrafa a mesma. Era este o falso positivo perigoso que o
--     documento de arranque já tinha apanhado (`nacional-touriga-vallado`
--     com `esporao-nacional-touriga`);
--   · o PRODUTOR — este não se resolve com uma lista, resolve-se abaixo:
--     a chave junta nome E produtor (de propósito, ver `winecatalog.achar`),
--     por isso dois vinhos diferentes da MESMA casa partilham sempre os
--     tokens dela. O "Leo d'Honor" e o "Ermelinda Freitas Syrah" são os
--     dois da Ermelinda Freitas e não têm mais nada em comum.
--
-- ESTA LISTA NÃO É A DO `base_nome`, e não tem de ser. Aquela decide
-- IDENTIDADE — mexer nela mexe na chave e, por aí, nas três apps. Esta só
-- decide se vale a pena PROPOR um par a uma pessoa, e por isso pode (e
-- deve) ser mais larga: aqui um falso negativo custa um duplicado que fica
-- mais um mês à espera, e um falso positivo custa a confiança na lista
-- toda — que é o que faz alguém carregar em "são o mesmo" sem olhar.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION winecatalog.generico(p_token text)
  RETURNS boolean LANGUAGE sql IMMUTABLE
  SET search_path TO 'winecatalog', 'public'
AS $$
  SELECT COALESCE(p_token, '') IN (
    -- gama, cor, estilo
    'reserva','grande','garrafeira','colheita','selecionada','seleccionada',
    'velhas','velha','superior','especial','premium','escolha','tinto','branco',
    'rose','doce','seco','bruto','meio','unoaked','barrica','madeira','antiga',
    'velho','novo','private','selection','edicao','limitada','safra','vindima',
    -- castas
    'touriga','nacional','franca','roriz','tinta','aragonez','trincadeira',
    'castelao','baga','jaen','alfrocheiro','alicante','bouschet','syrah','shiraz',
    'cabernet','sauvignon','merlot','pinot','noir','chardonnay','alvarinho',
    'loureiro','arinto','encruzado','fernao','pires','antao','vaz','verdelho',
    'viosinho','rabigato','gouveio','malvasia','moscatel','sercial','bual',
    'sousao','barroca','bastardo','ramisco','avesso','azal','trajadura','esgana',
    'cao','marufo','carignan','grenache','tempranillo','viognier','riesling',
    'semillon','petit','verdot','malbec','blend'
  );
$$;

-- ---------------------------------------------------------------------
-- CANDIDATOS: a lista que SUGERE, e que nunca decide
--
-- A trave está nas palavras que os dois lados partilham NO NOME e que
-- IDENTIFICAM mesmo um vinho (`fortes`). Tem de haver pelo menos uma —
-- senão o par não é proposto, por muito parecidas que as chaves sejam.
--
-- Repara que a contagem é sobre os tokens do NOME e não sobre os da
-- chave. É isso que apanha o terceiro ruído: a chave traz o produtor lá
-- dentro, e por isso dois vinhos diferentes da mesma casa parecem
-- parecidíssimos por tokens. Pelo nome, não: "Leo d'Honor" e "Ermelinda
-- Freitas Syrah" não têm uma palavra em comum.
--
-- Os cortes de antes ficam como estavam (>=2 tokens comuns, >=60% de
-- sobreposição): servem para medir QUÃO parecidas são duas chaves, e isso
-- continua a ser bom sinal. O que mudou é que já não chegam sozinhos.
--
-- A sobreposição mede-se contra o MENOR dos dois conjuntos: "Crasto" (1
-- token) contra "Crasto Reserva" (2) dá 100% e aparece na lista — que é o
-- que se quer. Contra o maior dava 50% e desaparecia.
--
-- Fora ficam: pares já marcados como distintos, linhas já fundidas
-- noutras, e colheitas diferentes (que nunca se fundem).
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION winecatalog.candidatos(p_limite integer DEFAULT 40)
  RETURNS jsonb
  LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE
  v_lim integer := LEAST(GREATEST(COALESCE(p_limite, 40), 1), 200);
  v_res jsonb;
BEGIN
  IF NOT winecatalog.pode_ler() THEN
    RAISE EXCEPTION 'Sem acesso ao catálogo.';
  END IF;

  WITH linhas AS (
    SELECT v.*,
           string_to_array(v.chave_base, '-') AS toks,
           winecatalog.tokens(v.nome)         AS toks_nome
      FROM winecatalog.vinhos v
     WHERE NOT EXISTS (SELECT 1 FROM winecatalog.alias a WHERE a.id_de = v.id)
  ), pares AS (
    SELECT a.id AS id_a, b.id AS id_b,
           a.chave AS chave_a, b.chave AS chave_b,
           cardinality(ARRAY(SELECT unnest(a.toks) INTERSECT SELECT unnest(b.toks))) AS comuns,
           LEAST(cardinality(a.toks), cardinality(b.toks)) AS menor,
           -- as palavras do NOME que os dois partilham e que identificam
           -- mesmo um vinho: nem gama, nem casta, nem só o produtor
           ARRAY(SELECT t FROM (
                   SELECT unnest(a.toks_nome) INTERSECT SELECT unnest(b.toks_nome)
                 ) x(t)
                  WHERE NOT winecatalog.generico(t)) AS fortes
      FROM linhas a
      JOIN linhas b
        ON b.id > a.id
       -- mesma colheita: duas colheitas nunca se fundem, por isso nem
       -- sequer se propõem
       AND b.ano IS NOT DISTINCT FROM a.ano
  ), filtrados AS (
    SELECT p.*, round(p.comuns::numeric / NULLIF(p.menor, 0), 2) AS sobreposicao
      FROM pares p
     WHERE cardinality(p.fortes) >= 1
       AND p.comuns >= 2
       AND p.menor > 0
       AND p.comuns::numeric / p.menor >= 0.6
       AND NOT EXISTS (
             SELECT 1 FROM winecatalog.distintos d
              WHERE d.chave_a = LEAST(p.chave_a, p.chave_b)
                AND d.chave_b = GREATEST(p.chave_a, p.chave_b))
  )
  SELECT COALESCE(jsonb_agg(jsonb_build_object(
           'comuns',       f.comuns,
           'sobreposicao', f.sobreposicao,
           -- vai para o ecrã: ver QUE palavra é que os aproximou é o que
           -- torna a decisão de um segundo em vez de um estudo
           'fortes',       to_jsonb(f.fortes),
           'a', winecatalog.resumo_linha(va.*),
           'b', winecatalog.resumo_linha(vb.*)
         ) ORDER BY f.sobreposicao DESC, f.comuns DESC), '[]'::jsonb)
    INTO v_res
    FROM (SELECT * FROM filtrados ORDER BY sobreposicao DESC, comuns DESC LIMIT v_lim) f
    JOIN winecatalog.vinhos va ON va.id = f.id_a
    JOIN winecatalog.vinhos vb ON vb.id = f.id_b;

  RETURN v_res;
END;
$$;

CREATE OR REPLACE FUNCTION winecatalog.marcar_distintos(p_id_a bigint, p_id_b bigint)
  RETURNS text LANGUAGE plpgsql SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE
  v_a text; v_b text;
BEGIN
  IF NOT winecatalog.sou_admin() THEN
    RAISE EXCEPTION 'Só o admin do catálogo pode decidir isto.';
  END IF;
  SELECT chave INTO v_a FROM winecatalog.vinhos WHERE id = p_id_a;
  SELECT chave INTO v_b FROM winecatalog.vinhos WHERE id = p_id_b;
  IF v_a IS NULL OR v_b IS NULL OR v_a = v_b THEN
    RAISE EXCEPTION 'Par inválido.';
  END IF;
  INSERT INTO winecatalog.distintos (chave_a, chave_b, quem)
  VALUES (LEAST(v_a, v_b), GREATEST(v_a, v_b), auth.email())
  ON CONFLICT (chave_a, chave_b) DO NOTHING;
  RETURN 'ok';
END;
$$;

-- E desfazer o "não são", que também é uma decisão e também se erra.
CREATE OR REPLACE FUNCTION winecatalog.desmarcar_distintos(p_chave_a text, p_chave_b text)
  RETURNS text LANGUAGE plpgsql SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
BEGIN
  IF NOT winecatalog.sou_admin() THEN
    RAISE EXCEPTION 'Só o admin do catálogo pode decidir isto.';
  END IF;
  DELETE FROM winecatalog.distintos
   WHERE chave_a = LEAST(p_chave_a, p_chave_b)
     AND chave_b = GREATEST(p_chave_a, p_chave_b);
  RETURN 'ok';
END;
$$;

-- A lista dos "não são" já gravados, para se poder voltar atrás sem ir ao
-- SQL Editor.
CREATE OR REPLACE FUNCTION winecatalog.listar_distintos()
  RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE v_res jsonb;
BEGIN
  IF NOT winecatalog.pode_ler() THEN
    RAISE EXCEPTION 'Sem acesso ao catálogo.';
  END IF;
  SELECT COALESCE(jsonb_agg(jsonb_build_object(
           'chaveA', d.chave_a, 'chaveB', d.chave_b,
           'nomeA', va.nome, 'nomeB', vb.nome,
           'quem', d.quem, 'quando', d.quando
         ) ORDER BY d.quando DESC), '[]'::jsonb)
    INTO v_res
    FROM winecatalog.distintos d
    LEFT JOIN winecatalog.vinhos va ON va.chave = d.chave_a
    LEFT JOIN winecatalog.vinhos vb ON vb.chave = d.chave_b;
  RETURN v_res;
END;
$$;




-- ---------------------------------------------------------------------
-- FUNDIR: "são o mesmo vinho"
--
-- `p_id_de` é a linha que deixa de responder por si; `p_id_para` é a que
-- fica. A UI propõe como alvo a mais preenchida, mas quem decide é quem
-- está a olhar.
--
-- Duas coisas acontecem, e a ordem importa:
--   1. os campos passam da perdedora para a alvo UM A UM, e só quando a
--      força de quem os tem é >= à de quem lá está. É a mesma regra da
--      `juntar`, e pela mesma razão: uma fusão não pode ser a porta dos
--      fundos por onde um número copiado à pressa tapa uma
--      `ws-verificacao` que se pagou. A força não se recalcula (não se
--      sabe aqui de que CAMPO ela veio do outro lado, e inventá-la era
--      pior): usa-se a que já está gravada em `origens`;
--   2. grava-se a linha em `winecatalog.alias`, e é ISSO que tira a
--      perdedora do caminho — a `achar()` passa a responder com a alvo
--      quando esbarra nela. **Não se lhe toca nas chaves nem na ficha.**
--
-- O que fica em `campos_movidos` é o estado ANTERIOR de cada campo
-- mexido, para o `separar` ser exato e não um palpite.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION winecatalog.fundir(p_id_de bigint, p_id_para bigint)
  RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE
  de    winecatalog.vinhos%ROWTYPE;
  para  winecatalog.vinhos%ROWTYPE;
  v_ficha   jsonb;
  v_origens jsonb;
  v_fontes  jsonb;
  v_mov     jsonb := '{}'::jsonb;
  k     text;
  v     jsonb;
  f_de  integer;
  f_para integer;
BEGIN
  IF NOT winecatalog.sou_admin() THEN
    RAISE EXCEPTION 'Só o admin do catálogo pode fundir linhas.';
  END IF;
  IF p_id_de IS NULL OR p_id_para IS NULL OR p_id_de = p_id_para THEN
    RAISE EXCEPTION 'Par inválido.';
  END IF;

  SELECT * INTO de   FROM winecatalog.vinhos WHERE id = p_id_de   FOR UPDATE;
  SELECT * INTO para FROM winecatalog.vinhos WHERE id = p_id_para FOR UPDATE;
  IF de.id IS NULL OR para.id IS NULL THEN
    RAISE EXCEPTION 'Linha não encontrada.';
  END IF;
  IF EXISTS (SELECT 1 FROM winecatalog.alias WHERE id_de = de.id) THEN
    RAISE EXCEPTION 'Essa linha já foi fundida noutra.';
  END IF;
  -- Fundir A em B quando B já foi fundida em C deixava uma cadeia que a
  -- `achar` não segue (resolve UM salto, de propósito — uma cadeia é um
  -- ciclo à espera de acontecer).
  IF EXISTS (SELECT 1 FROM winecatalog.alias WHERE id_de = para.id) THEN
    RAISE EXCEPTION 'A linha escolhida para ficar já foi fundida noutra — desfaz essa primeiro.';
  END IF;

  -- A trave que segura a nota e o preço. Não é um aviso: é um erro.
  IF de.ano IS DISTINCT FROM para.ano
     AND de.ano IS NOT NULL AND para.ano IS NOT NULL THEN
    RAISE EXCEPTION 'São colheitas diferentes (% e %) — essas nunca se fundem.',
      de.ano, para.ano;
  END IF;

  v_ficha   := para.ficha;
  v_origens := para.origens;
  v_fontes  := COALESCE(para.fontes, '[]'::jsonb);

  FOR k, v IN SELECT key, value FROM jsonb_each(de.ficha) LOOP
    CONTINUE WHEN v IS NULL OR jsonb_typeof(v) = 'null'
                  OR v = '""'::jsonb OR v = '[]'::jsonb OR v = '{}'::jsonb;
    f_de   := COALESCE((de.origens -> k ->> 'f')::integer, 0);
    f_para := COALESCE((v_origens  -> k ->> 'f')::integer, 0);
    IF NOT (v_ficha ? k) OR f_de >= f_para THEN
      v_mov := v_mov || jsonb_build_object(k, jsonb_build_object(
        'antes',         CASE WHEN v_ficha ? k THEN v_ficha -> k END,
        'antes_origem',  v_origens -> k,
        'depois_origem', COALESCE(de.origens -> k, '{}'::jsonb)
      ));
      v_ficha   := v_ficha   || jsonb_build_object(k, v);
      v_origens := v_origens || jsonb_build_object(k, COALESCE(de.origens -> k, '{}'::jsonb));
    END IF;
  END LOOP;

  -- As fontes juntam-se sem repetir e ficam pelas 8, como na `juntar`:
  -- são para se poder ir ver de onde veio isto, não um arquivo.
  SELECT COALESCE(jsonb_agg(f), '[]'::jsonb) INTO v_fontes FROM (
    SELECT DISTINCT ON (f ->> 'url') f
      FROM jsonb_array_elements(v_fontes || COALESCE(de.fontes, '[]'::jsonb)) f
     WHERE COALESCE(f ->> 'url', '') <> ''
     ORDER BY (f ->> 'url')
     LIMIT 8
  ) x;

  UPDATE winecatalog.vinhos SET
    ficha    = v_ficha,
    origens  = v_origens,
    fontes   = v_fontes,
    -- o nome mais COMPRIDO fica, como na `juntar`
    nome     = CASE WHEN length(COALESCE(de.nome,'')) > length(nome) THEN de.nome ELSE nome END,
    produtor = CASE WHEN produtor = '' THEN COALESCE(de.produtor,'') ELSE produtor END,
    ano      = COALESCE(ano, de.ano),
    atualizado_em = now()
  WHERE id = para.id;

  INSERT INTO winecatalog.alias (chave_de, chave_para, id_de, id_para,
                                 nome_de, ano_de, campos_movidos, quem)
  VALUES (de.chave, para.chave, de.id, para.id, de.nome, de.ano, v_mov, auth.email())
  ON CONFLICT (chave_de) DO UPDATE
    SET chave_para = EXCLUDED.chave_para, id_para = EXCLUDED.id_para,
        campos_movidos = EXCLUDED.campos_movidos, quem = EXCLUDED.quem,
        quando = now();

  -- Um par fundido deixa de ser um par por decidir.
  DELETE FROM winecatalog.distintos
   WHERE chave_a = LEAST(de.chave, para.chave)
     AND chave_b = GREATEST(de.chave, para.chave);

  RETURN jsonb_build_object(
    'ok', true, 'id', para.id,
    'campos', (SELECT count(*) FROM jsonb_object_keys(v_mov))
  );
END;
$$;


-- ---------------------------------------------------------------------
-- SEPARAR: desfazer uma fusão — literalmente apagar uma linha
--
-- A perdedora volta a responder por si assim que o alias desaparece (é a
-- `achar` que deixa de a desviar), e cada campo volta ao que era ANTES da
-- fusão — mas SÓ os campos que ninguém reescreveu entretanto. A
-- comparação é com a entrada de `origens` que a fusão lá pôs: se ela
-- ainda está exatamente igual, ninguém tocou; se mudou, foi outra escrita
-- e essa manda.
--
-- Desfazer uma fusão de setembro não pode deitar fora uma verificação de
-- outubro — é por isso que isto não é um "restaurar a cópia de segurança"
-- em bloco.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION winecatalog.separar(p_chave_de text)
  RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE
  a     winecatalog.alias%ROWTYPE;
  para  winecatalog.vinhos%ROWTYPE;
  v_ficha   jsonb;
  v_origens jsonb;
  k     text;
  v     jsonb;
  n_rep integer := 0;
  n_mant integer := 0;
BEGIN
  IF NOT winecatalog.sou_admin() THEN
    RAISE EXCEPTION 'Só o admin do catálogo pode desfazer uma fusão.';
  END IF;

  SELECT * INTO a FROM winecatalog.alias WHERE chave_de = p_chave_de;
  IF a.chave_de IS NULL THEN RAISE EXCEPTION 'Essa fusão não existe.'; END IF;

  SELECT * INTO para FROM winecatalog.vinhos WHERE id = a.id_para FOR UPDATE;
  IF para.id IS NOT NULL THEN
    v_ficha   := para.ficha;
    v_origens := para.origens;
    FOR k, v IN SELECT key, value FROM jsonb_each(a.campos_movidos) LOOP
      IF (v_origens -> k) IS NOT DISTINCT FROM (v -> 'depois_origem') THEN
        IF (v -> 'antes') IS NULL OR jsonb_typeof(v -> 'antes') = 'null' THEN
          v_ficha   := v_ficha   - k;      -- não estava lá: volta a não estar
          v_origens := v_origens - k;
        ELSE
          v_ficha   := v_ficha   || jsonb_build_object(k, v -> 'antes');
          v_origens := v_origens || jsonb_build_object(k, COALESCE(v -> 'antes_origem', '{}'::jsonb));
        END IF;
        n_rep := n_rep + 1;
      ELSE
        n_mant := n_mant + 1;              -- alguém escreveu depois: fica
      END IF;
    END LOOP;
    UPDATE winecatalog.vinhos
       SET ficha = v_ficha, origens = v_origens, atualizado_em = now()
     WHERE id = para.id;
  END IF;

  DELETE FROM winecatalog.alias WHERE chave_de = a.chave_de;

  RETURN jsonb_build_object('ok', true, 'repostos', n_rep, 'mantidos', n_mant);
END;
$$;
-- =====================================================================
-- 4. O TAMANHO DO CATÁLOGO, E DE ONDE VEIO CADA CAMPO
--
-- A segunda metade do ecrã de Resumo. "Quantos campos vieram de cada
-- origem" é a pergunta que apanhou a avaria que esteve semanas de pé: os
-- 3106 campos do catálogo estavam TODOS a força 3, nenhum tinha entrado
-- por uma pesquisa, e nenhum podia, porque 3 tapa 2. Um número destes no
-- ecrã tê-la-ia apanhado no primeiro dia.
-- =====================================================================
CREATE OR REPLACE FUNCTION winecatalog.resumo()
  RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE v_res jsonb;
BEGIN
  IF NOT winecatalog.pode_ler() THEN
    RAISE EXCEPTION 'Sem acesso ao catálogo.';
  END IF;

  WITH vivas AS (
    SELECT v.* FROM winecatalog.vinhos v WHERE NOT EXISTS (SELECT 1 FROM winecatalog.alias a WHERE a.id_de = v.id)
  ), campos AS (
    SELECT o.key AS campo,
           COALESCE(o.value ->> 'o', '(sem origem)') AS origem,
           COALESCE((o.value ->> 'f')::integer, 0)   AS forca
      FROM vivas v, jsonb_each(v.origens) o
  )
  SELECT jsonb_build_object(
    'linhas',        (SELECT count(*) FROM vivas),
    'distintos',     (SELECT count(DISTINCT chave_base) FROM vivas),
    'semAno',        (SELECT count(*) FROM vivas WHERE ano IS NULL),
    'campos',        (SELECT count(*) FROM campos),
    'mediaCampos',   (SELECT round(AVG(n), 1) FROM (
                        SELECT (SELECT count(*) FROM jsonb_object_keys(v.ficha)) AS n
                          FROM vivas v) t),
    'fundidas',      (SELECT count(*) FROM winecatalog.alias),
    'distintosMarcados', (SELECT count(*) FROM winecatalog.distintos),
    -- quantos campos por ORIGEM, e a que força entraram
    'origens', COALESCE((
        SELECT jsonb_agg(jsonb_build_object('origem', c.origem, 'forca', c.forca, 'campos', c.n)
                         ORDER BY c.n DESC)
          FROM (SELECT origem, forca, count(*) AS n FROM campos GROUP BY origem, forca) c
      ), '[]'::jsonb),
    -- e quantos campos VOLÁTEIS estão velhos (>30 dias): é o que as apps
    -- vão pedir outra vez à IA na próxima pergunta
    'volateisVelhos', (
        SELECT count(*) FROM vivas v, jsonb_each(v.origens) o
         WHERE winecatalog.volatil(o.key)
           AND COALESCE((o.value ->> 'em')::timestamptz, v.criado_em) < now() - interval '30 days')
  ) INTO v_res;

  RETURN v_res;
END;
$$;


-- ---------------------------------------------------------------------
-- SYNC_LOG — o que a Edge Function desta app gastou
--
-- As outras duas apps têm a sua (`garrafeira.sync_log`,
-- `wineselection.sync_log`) e a vista `winecatalog.consumo` já as lê. A
-- partir do momento em que ESTA app também manda pesquisar, também gasta
-- — e um gasto que não aparece no ecrã do "está a poupar quanto?" faz o
-- número mentir por omissão. Mesma forma das outras duas, de propósito:
-- é o que deixa a vista juntá-las sem casos especiais.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS winecatalog.sync_log (
  id        bigint GENERATED BY DEFAULT AS IDENTITY,
  origem    text NOT NULL DEFAULT 'function',   -- 'function' | 'app'
  acao      text NOT NULL,
  estado    text NOT NULL,                      -- 'pedido' | 'ok' | 'erro'
  quem      text,
  detalhe   jsonb NOT NULL DEFAULT '{}'::jsonb,
  criado_em timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sync_log_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS sync_log_criado_idx ON winecatalog.sync_log (criado_em DESC);
ALTER TABLE winecatalog.sync_log ENABLE ROW LEVEL SECURITY;


-- =====================================================================
-- 5. O CONSUMO DAS OUTRAS DUAS APPS — `winecatalog.consumo`
--
-- A pergunta que deu origem ao catálogo ("está a poupar quanto?") tem a
-- resposta em `garrafeira.sync_log` e `wineselection.sync_log` — duas
-- tabelas em dois schemas que a WineCatalog não tem (nem deve ter) que
-- conhecer. A vista põe as duas na mesma forma, e a app fala só com o
-- `winecatalog`, sem espreitar para dentro das outras duas.
--
-- AS UNIDADES NÃO SÃO A MESMA COISA, e somá-las era inventar um número:
--   · a `vinho-info` conta CAMPOS   (castas, região, teor…);
--   · a `sugerir-vinho` conta NOTAS (uma por vinho da carta);
--   · a `verificar-vinhos` conta VINHOS.
-- Por isso cada linha diz em que UNIDADE está, e quem soma só soma dentro
-- da mesma. O que atravessa as três e se pode somar é o PEDIDO: um pedido
-- que não foi à IA nenhuma vez (`so_catalogo`) é uma ida poupada, e essa
-- conta-se igual nas três.
--
-- O CUSTO: `custo_estimado_eur` vem dos próprios logs, e onde não vem é
-- porque não houve chamada nenhuma (a `vinho-info` servida pelo catálogo
-- nem sequer escreve o campo) — daí o zero. É uma ESTIMATIVA GROSSEIRA,
-- não um preço publicado, e a pesquisa Google é faturada à parte por
-- pedido. Os TOKENS é que são facto: vêm da API do Gemini. O ecrã tem de
-- dizer as duas coisas.
--
-- SEGURANÇA: uma vista não é `security_invoker`, corre como o DONO, e o
-- dono aqui passa por cima da RLS das duas `sync_log`. Ou seja: esta vista
-- vê tudo, INCLUINDO o `quem` de cada pedido. Por isso não se dá SELECT
-- dela a ninguém (ver os REVOKEs no fim) e quem lhe chega é só a
-- `ia_uso.poupanca_catalogo()` da AI-API-Control (ver abaixo), que agrega
-- e NUNCA devolve o `quem` — quanto é que o catálogo poupou não precisa de
-- dizer quem é que andou a usar o quê.
-- =====================================================================

-- Ler um número de um jsonb sem rebentar se lá estiver um texto. Um
-- `(detalhe->>'x')::numeric` seco morre com a linha inteira no dia em que
-- alguém gravar "n/d" — e o ecrã ficava em branco sem se perceber porquê.
CREATE OR REPLACE FUNCTION winecatalog.num(p jsonb, k text)
  RETURNS numeric LANGUAGE sql IMMUTABLE
  SET search_path TO 'winecatalog', 'public'
AS $$
  SELECT CASE WHEN jsonb_typeof(p -> k) = 'number' THEN (p ->> k)::numeric ELSE 0 END;
$$;

CREATE OR REPLACE VIEW winecatalog.consumo AS
  -- Garrafeira / vinho-info — conta CAMPOS.
  -- Só `origem='function'`: as linhas com origem 'app' são outro tipo de
  -- registo (a app a anotar-se a si própria) e não são pedidos à IA.
  SELECT 'garrafeira'::text AS app,
         l.acao,
         l.estado,
         l.criado_em,
         COALESCE(l.detalhe ->> 'modo', '')                  AS modo,
         (COALESCE(l.detalhe ->> 'modo', '') = 'catalogo')    AS so_catalogo,
         'campos'::text                                      AS unidade,
         CASE WHEN COALESCE(l.detalhe ->> 'modo', '') = 'catalogo'
              THEN winecatalog.num(l.detalhe, 'campos')
              ELSE winecatalog.num(l.detalhe, 'catalogo_campos') END AS itens_catalogo,
         winecatalog.num(l.detalhe, 'ia_campos')                 AS itens_ia,
         winecatalog.num(l.detalhe, 'custo_estimado_eur')        AS custo_eur,
         winecatalog.num(l.detalhe -> 'usageMetadata', 'totalTokenCount') AS tokens
    FROM garrafeira.sync_log l
   WHERE l.origem = 'function'

  UNION ALL

  -- WineSelection / sugerir-vinho — conta NOTAS da carta.
  -- `so_catalogo` é sempre falso e não é um esquecimento: esta chamada lê
  -- uma FOTOGRAFIA, e isso não há catálogo que o responda. O que o
  -- catálogo aqui poupa é a SEGUNDA chamada (a das notas), e isso
  -- aparece em `itens_catalogo`.
  SELECT 'wineselection'::text,
         l.acao,
         l.estado,
         l.criado_em,
         COALESCE(l.detalhe ->> 'modelo', ''),
         false,
         'notas'::text,
         winecatalog.num(l.detalhe, 'pontuacoes_catalogo'),
         GREATEST(winecatalog.num(l.detalhe, 'pontuacoes_aprox')
                  - winecatalog.num(l.detalhe, 'pontuacoes_catalogo'), 0),
         winecatalog.num(l.detalhe, 'custo_estimado_eur'),
         winecatalog.num(l.detalhe -> 'usageMetadata', 'totalTokenCount')
    FROM wineselection.sync_log l
   WHERE l.acao = 'sugerir_vinho'

  UNION ALL

  -- WineSelection / verificar-vinhos — conta VINHOS. É a mais cara das
  -- três (pesquisa Google a sério), e a única da WineSelection que o
  -- catálogo pode servir inteira.
  SELECT 'wineselection'::text,
         l.acao,
         l.estado,
         l.criado_em,
         COALESCE(l.detalhe ->> 'modelo', ''),
         (COALESCE(l.detalhe ->> 'modelo', '') = 'catalogo'),
         'vinhos'::text,
         winecatalog.num(l.detalhe, 'catalogo'),
         winecatalog.num(l.detalhe, 'gemini'),
         winecatalog.num(l.detalhe, 'custo_estimado_eur'),
         winecatalog.num(l.detalhe -> 'usageMetadata', 'totalTokenCount')
    FROM wineselection.sync_log l
   WHERE l.acao = 'verificar_vinhos'

  UNION ALL

  -- WineCatalog / catalogo-info — conta CAMPOS, como a `vinho-info`, e é
  -- a mesma pergunta feita do outro lado: aqui não há garrafeira nenhuma,
  -- há o admin a mandar pesquisar uma linha do catálogo.
  --
  -- `so_catalogo` é SEMPRE falso, e desta vez não é um pormenor: esta
  -- chamada existe precisamente para ir buscar o que o catálogo NÃO tem.
  -- Servi-la pelo catálogo seria devolver a pergunta a quem a fez. Por
  -- isso esta app só aparece no ecrã do lado do GASTO — e é bom que
  -- apareça: a partir do momento em que o catálogo também paga, um número
  -- de poupança que a ignorasse estava a mentir por omissão.
  SELECT 'winecatalog'::text,
         l.acao,
         l.estado,
         l.criado_em,
         COALESCE(l.detalhe ->> 'modelo', ''),
         false,
         'campos'::text,
         0::numeric,
         winecatalog.num(l.detalhe, 'campos'),
         winecatalog.num(l.detalhe, 'custo_estimado_eur'),
         winecatalog.num(l.detalhe -> 'usageMetadata', 'totalTokenCount')
    FROM winecatalog.sync_log l
   WHERE l.origem = 'function';



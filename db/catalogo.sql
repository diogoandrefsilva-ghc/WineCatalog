-- QUEM PODE CHAMAR O QUÊ
--
-- O schema `winecatalog` está EXPOSTO na API (é assim que a app e as três
-- Edge Functions lhe falam) e uma função SECURITY DEFINER nasce com
-- EXECUTE para PUBLIC. As duas coisas juntas são um caminho direto para
-- dentro se alguém se esquecer de um REVOKE.
--
-- LEIA-SE ISTO COM ATENÇÃO, que é o ponto onde a mudança de casa podia
-- ter aberto um buraco: enquanto o catálogo viveu num schema só dele, a
-- `vinhos` estava protegida por DUAS coisas — RLS sem policy nenhuma E
-- nenhum GRANT a `anon`/`authenticated`. Ao vir para o schema da APP, um
-- `GRANT ALL ON ALL TABLES IN SCHEMA winecatalog TO anon, authenticated`
-- (que é o que as apps irmãs fazem no schema delas, e que este repo
-- chegou a ter) apanhava-a de caminho e deixava-a só com a RLS. Continuava
-- fechada — mas por uma trave em vez de duas, e sem ninguém dar por isso.
--
-- Por isso o `db/schema.sql` NÃO dá grants em bloco neste schema: dá-os
-- tabela a tabela, e as do catálogo não estão lá. Se um dia acrescentares
-- uma tabela aqui, a pergunta a fazer é a mesma: isto é da APP (e leva
-- GRANT + policies) ou é do CATÁLOGO (e não leva nada)?
-- =====================================================================

-- As três tabelas do catálogo e a config: nenhum GRANT a quem tem login.
-- Só a service role (Edge Functions) e as funções SECURITY DEFINER.

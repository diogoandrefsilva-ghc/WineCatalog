REVOKE ALL ON winecatalog.alias     FROM PUBLIC, anon, authenticated;
REVOKE ALL ON winecatalog.distintos FROM PUBLIC, anon, authenticated;
REVOKE ALL ON winecatalog.config    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON winecatalog.consumo   FROM PUBLIC, anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON winecatalog.vinhos    TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON winecatalog.alias     TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON winecatalog.distintos TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON winecatalog.config    TO service_role;
REVOKE ALL ON winecatalog.sync_log FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON winecatalog.sync_log TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA winecatalog    TO service_role;

-- As TRÊS das Edge Functions: service role e mais ninguém. Sem isto,

-- em `historico.sql` para ver e repor).
--
-- A mesma regra da `juntar`, campo a campo: entra se o campo está vazio ou
-- se a força desta origem (`forca(origem, campo)`) é igual ou maior do que
-- a que lá está. Um valor escrito à mão no rótulo (4) nunca é tapado; uma
-- nota lida na página do Vivino (3) atualiza a que lá estava. Pelo ID e não
-- pela chave: o script já sabe de que linha se trata.
--
-- Diz o que entrou e o que ficou de fora (e porquê) — é o que o script
-- mostra no fim de cada vinho.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION winecatalog.aplicar_fontes(
  p_vinho_id bigint, p_campos jsonb, p_origem text, p_quem text,
  p_fontes jsonb DEFAULT '[]'::jsonb
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE
  v_id      bigint;
  v_ficha   jsonb;
  v_origens jsonb;
  v_fontes  jsonb;
  v_entrou  jsonb := '[]'::jsonb;
  v_ficou   jsonb := '[]'::jsonb;
  k         text;
  v         jsonb;
  v_f       integer;
  v_ant     integer;
BEGIN
  IF COALESCE(auth.role(), '') <> 'service_role' THEN
    RAISE EXCEPTION 'Só o batch (service_role) chama isto.';
  END IF;
  IF winecatalog.forca(p_origem) <= 0 THEN
    RAISE EXCEPTION 'Origem sem força: %', p_origem;
  END IF;
  v_id := COALESCE((SELECT id_para FROM winecatalog.alias WHERE id_de = p_vinho_id), p_vinho_id);
  SELECT ficha, origens, fontes INTO v_ficha, v_origens, v_fontes
    FROM winecatalog.vinhos WHERE id = v_id FOR UPDATE;
  IF v_ficha IS NULL THEN RAISE EXCEPTION 'Vinho % não existe.', p_vinho_id; END IF;

  PERFORM set_config('winecatalog.quem', COALESCE(NULLIF(p_quem, ''), 'script'), true);

  FOR k, v IN SELECT key, value FROM jsonb_each(COALESCE(p_campos, '{}')) LOOP
    CONTINUE WHEN k !~ '^[a-z][a-z0-9_]{0,39}$' OR winecatalog.vazio(v);
    -- A mesma normalização da `juntar`/`criar`: "DOURO" não entra assim.
    IF k = 'regiao' AND jsonb_typeof(v) = 'string' THEN
      v := to_jsonb(winecatalog.normalizar_regiao(v #>> '{}'));
    END IF;
    v_f   := winecatalog.forca(p_origem, k);
    v_ant := COALESCE((v_origens -> k ->> 'f')::integer, 0);
    IF v_f >= v_ant THEN
      v_ficha   := v_ficha || jsonb_build_object(k, v);
      v_origens := v_origens || jsonb_build_object(k, jsonb_build_object('o', p_origem, 'f', v_f, 'em', now()));
      v_entrou  := v_entrou || to_jsonb(k);
    ELSE
      v_ficou := v_ficou || jsonb_build_object('campo', k, 'origem', v_origens -> k ->> 'o', 'forca', v_ant);
    END IF;
  END LOOP;

  IF p_fontes IS NOT NULL AND jsonb_typeof(p_fontes) = 'array' AND jsonb_array_length(p_fontes) > 0 THEN
    SELECT COALESCE(jsonb_agg(f), '[]'::jsonb) INTO v_fontes FROM (
      SELECT DISTINCT ON (f ->> 'url') f
        FROM jsonb_array_elements(COALESCE(v_fontes, '[]') || p_fontes) f
       WHERE COALESCE(f ->> 'url', '') <> ''
       ORDER BY (f ->> 'url') LIMIT 8) x;
  END IF;

  UPDATE winecatalog.vinhos
     SET ficha = v_ficha, origens = v_origens, fontes = COALESCE(v_fontes, fontes),
         atualizado_em = CASE WHEN jsonb_array_length(v_entrou) > 0 THEN now() ELSE atualizado_em END
   WHERE id = v_id;
  RETURN jsonb_build_object('vinho', v_id, 'entrou', v_entrou, 'ficou', v_ficou);
END;
$$;


-- ---------------------------------------------------------------------
-- VINHO NOVO pelo painel do vinhos.bat (25/09/2026). O admin escreve nome,
-- produtor, ano e cor; o script procura no Vivino e nas lojas e só DEPOIS de
-- o admin rever a simulação é que a linha nasce.
-- `vivino_achar`: já existe? (a MESMA `achar` do `juntar`/`criar`, às duas
-- chaves). `vivino_novo`: cria pela `criar` — que recusa um duplicado —, ou
-- devolve a que já existe se entretanto alguém a criou.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION winecatalog.vivino_achar(p_nome text, p_produtor text, p_ano integer)
  RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE v_id bigint; v winecatalog.vinhos;
BEGIN
  IF COALESCE(auth.role(), '') <> 'service_role' THEN
    RAISE EXCEPTION 'Só o batch (service_role) chama isto.';
  END IF;
  v_id := winecatalog.achar(btrim(COALESCE(p_nome, '')), COALESCE(p_produtor, ''), p_ano, true);
  IF v_id IS NULL THEN RETURN NULL; END IF;
  v_id := COALESCE((SELECT id_para FROM winecatalog.alias WHERE id_de = v_id), v_id);
  SELECT * INTO v FROM winecatalog.vinhos WHERE id = v_id;
  RETURN winecatalog.vivino_linha(v);
END;
$$;

CREATE OR REPLACE FUNCTION winecatalog.vivino_novo(
  p_nome text, p_produtor text, p_ano integer, p_tipo text, p_quem text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE v_ja jsonb; v_r jsonb;
BEGIN
  IF COALESCE(auth.role(), '') <> 'service_role' THEN
    RAISE EXCEPTION 'Só o batch (service_role) chama isto.';
  END IF;
  v_ja := winecatalog.vivino_achar(p_nome, p_produtor, p_ano);
  IF v_ja IS NOT NULL THEN
    RETURN jsonb_build_object('id', v_ja -> 'id', 'existia', true);
  END IF;
  PERFORM set_config('winecatalog.quem', COALESCE(NULLIF(p_quem, ''), 'script'), true);
  -- A cor foi o admin que a escolheu no painel: entra como uma correção à
  -- mão (a `criar` dá-lhe a força de `catalogo-admin`).
  v_r := winecatalog.criar(p_nome, COALESCE(p_produtor, ''), p_ano,
           CASE WHEN COALESCE(p_tipo, '') <> '' THEN jsonb_build_object('tipo', p_tipo) ELSE '{}'::jsonb END);
  RETURN jsonb_build_object('id', v_r -> 'id', 'existia', false);
END;
$$;


-- ---------------------------------------------------------------------
-- ESCOLHER NO PAINEL (25/09/2026). O painel do vinhos.bat mostra o catálogo
-- e o admin marca os vinhos a tratar. `vivino_catalogo`: a lista, leve (o
-- que ajuda a escolher — tem fotografia? preço? quando foi visto?), sem os
-- fundidos. `vivino_estes`: esses vinhos, na forma que o script recebe, pela
-- ordem marcada; um id fundido responde pelo vinho que ficou.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION winecatalog.vivino_catalogo()
  RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
BEGIN
  IF COALESCE(auth.role(), '') <> 'service_role' THEN
    RAISE EXCEPTION 'Só o batch (service_role) chama isto.';
  END IF;
  RETURN COALESCE((
    SELECT jsonb_agg(jsonb_build_object(
      'id', v.id, 'nome', v.nome, 'produtor', v.produtor, 'ano', v.ano,
      'tipo', v.ficha ->> 'tipo', 'regiao', v.ficha ->> 'regiao',
      'imagem', v.ficha ? 'imagem_url', 'preco', v.ficha ? 'preco_medio', 'vivino', v.ficha ? 'vivino_url',
      -- O formato do link: 'ok' (/<nome>/w/<nº>, limpo), 'por_limpar' (tem o
      -- número do vinho mas também país/língua/?year= — funciona, e o script
      -- arruma-o quando passa), 'invalido' (sem /w/<nº>: /wines/<nº> é UMA
      -- colheita, /Wines/<nome> não existe — o que as pesquisas de memória
      -- inventam). A mesma regra do `urlLimpo` do script.
      'link', CASE WHEN COALESCE(v.ficha ->> 'vivino_url', '') = '' THEN NULL
                   WHEN v.ficha ->> 'vivino_url' ~ '^https://www\.vivino\.com/[a-z0-9-]+/w/[0-9]+$' THEN 'ok'
                   WHEN v.ficha ->> 'vivino_url' ~ '^https?://([a-z]+\.)?vivino\.com/.*/w/[0-9]+' THEN 'por_limpar'
                   ELSE 'invalido' END,
      'campos', (SELECT count(*) FROM jsonb_object_keys(v.ficha)),
      'visto', (SELECT max(x.verificado_em) FROM winecatalog.vivino_verificacoes x WHERE x.vinho_id = v.id))
      ORDER BY lower(v.nome), v.ano NULLS FIRST)
    FROM winecatalog.vinhos v
    WHERE NOT EXISTS (SELECT 1 FROM winecatalog.alias a WHERE a.id_de = v.id)), '[]'::jsonb);
END;
$$;

CREATE OR REPLACE FUNCTION winecatalog.vivino_estes(p_ids bigint[])
  RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
BEGIN
  IF COALESCE(auth.role(), '') <> 'service_role' THEN
    RAISE EXCEPTION 'Só o batch (service_role) chama isto.';
  END IF;
  RETURN COALESCE((
    SELECT jsonb_agg(winecatalog.vivino_linha(v) ORDER BY o.ord)
      FROM (SELECT DISTINCT ON (alvo) alvo, ord FROM (
              SELECT COALESCE((SELECT id_para FROM winecatalog.alias WHERE id_de = i), i) alvo, ord
                FROM unnest(p_ids[1:50]) WITH ORDINALITY AS u(i, ord)) z
            ORDER BY alvo, ord) o
      JOIN winecatalog.vinhos v ON v.id = o.alvo), '[]'::jsonb);
END;
$$;



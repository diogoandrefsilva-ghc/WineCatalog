-- Um vinho como o script o recebe. A ficha vai inteira: o script só
-- preenche os campos VAZIOS dela (castas, região, harmonização…) e tem de
-- saber quais são. Uma função só, para a fila e para o "Vinho novo".
CREATE OR REPLACE FUNCTION winecatalog.vivino_linha(v winecatalog.vinhos)
  RETURNS jsonb LANGUAGE sql STABLE
  SET search_path TO 'winecatalog', 'public'
AS $$
  SELECT jsonb_build_object(
    'id', v.id, 'nome', v.nome, 'produtor', v.produtor, 'ano', v.ano,
    'tipo', v.ficha ->> 'tipo',
    'vivino_url', v.ficha ->> 'vivino_url',
    'vivino_nota', v.ficha -> 'vivino_nota',
    'vivino_avaliacoes', v.ficha -> 'vivino_avaliacoes',
    'preco_medio', v.ficha -> 'preco_medio',
    'precos', v.ficha -> 'precos',
    -- De onde veio o preço médio e a imagem: no modo "só o Vivino" um preço
    -- de loja não se toca, e só se troca uma imagem que também veio do Vivino.
    'origem_preco', v.origens -> 'preco_medio' ->> 'o',
    'origem_imagem', v.origens -> 'imagem_url' ->> 'o',
    'ficha', v.ficha);
$$;

-- Hoje é dia? E, se for, que vinhos? Primeiro os da fila (pedidos à mão),
-- depois os que nunca foram vistos, depois os vistos há mais tempo. Quem
-- ainda tem uma verificação por decidir fica de fora — voltar a verificá-lo
-- era só acumular propostas para o mesmo vinho.
CREATE OR REPLACE FUNCTION winecatalog.vivino_a_tratar(
  p_manual boolean DEFAULT false, p_limite integer DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE
  v_freq  text;
  v_lote  integer;
  v_fila  jsonb;
  v_ult   date;
  v_hoje  date := (now() AT TIME ZONE 'Europe/Lisbon')::date;
  v_dia   boolean;
  v_ids   bigint[];
  v_resto integer;
BEGIN
  IF COALESCE(auth.role(), '') <> 'service_role' THEN
    RAISE EXCEPTION 'Só o batch (service_role) chama isto.';
  END IF;
  v_freq := COALESCE((SELECT valor FROM winecatalog.config WHERE chave = 'vivino_frequencia'), 'desligado');
  v_lote := COALESCE(p_limite, (SELECT valor FROM winecatalog.config WHERE chave = 'vivino_lote')::int, 10);
  v_lote := GREATEST(1, LEAST(v_lote, 50));
  v_fila := COALESCE((SELECT valor::jsonb FROM winecatalog.config WHERE chave = 'vivino_fila'), '[]');
  v_ult  := ((SELECT valor FROM winecatalog.config WHERE chave = 'vivino_ultima')::timestamptz
              AT TIME ZONE 'Europe/Lisbon')::date;

  v_dia := CASE v_freq
    WHEN 'diario'          THEN v_ult IS NULL OR v_hoje - v_ult >= 1
    WHEN 'dia_sim_dia_nao' THEN v_ult IS NULL OR v_hoje - v_ult >= 2
    WHEN 'semanal'         THEN v_ult IS NULL OR v_hoje - v_ult >= 7
    ELSE false END;

  IF NOT p_manual AND NOT v_dia AND jsonb_array_length(v_fila) = 0 THEN
    RETURN jsonb_build_object('correr', false,
      'motivo', format('frequência "%s", última execução %s', v_freq, COALESCE(v_ult::text, 'nunca')));
  END IF;

  -- A fila primeiro, pela ordem em que foi pedida.
  SELECT COALESCE(array_agg(i ORDER BY ord), '{}') INTO v_ids FROM (
    SELECT value::bigint i, ordinality ord
      FROM jsonb_array_elements_text(v_fila) WITH ORDINALITY
     WHERE EXISTS (SELECT 1 FROM winecatalog.vinhos v WHERE v.id = value::bigint)
       AND NOT EXISTS (SELECT 1 FROM winecatalog.alias a WHERE a.id_de = value::bigint)
     LIMIT v_lote
  ) f;

  -- Só a fila, quando hoje não é dia: foram pedidos, o resto não.
  v_resto := CASE WHEN p_manual OR v_dia THEN v_lote - COALESCE(array_length(v_ids, 1), 0) ELSE 0 END;
  IF v_resto > 0 THEN
    v_ids := v_ids || COALESCE((
      SELECT array_agg(id ORDER BY ult NULLS FIRST, id) FROM (
        SELECT v.id, (SELECT max(verificado_em) FROM winecatalog.vivino_verificacoes x
                       WHERE x.vinho_id = v.id) ult
          FROM winecatalog.vinhos v
         WHERE NOT (v.id = ANY(v_ids))
           AND NOT EXISTS (SELECT 1 FROM winecatalog.alias a WHERE a.id_de = v.id)
           AND NOT EXISTS (SELECT 1 FROM winecatalog.vivino_verificacoes x
                            WHERE x.vinho_id = v.id AND x.revisao = 'pendente')
         ORDER BY ult NULLS FIRST, v.id
         LIMIT v_resto
      ) s), '{}');
  END IF;

  RETURN jsonb_build_object('correr', COALESCE(array_length(v_ids, 1), 0) > 0,
    'motivo', CASE WHEN p_manual THEN 'manual' WHEN v_dia THEN v_freq ELSE 'fila' END,
    'vinhos', COALESCE((
      SELECT jsonb_agg(winecatalog.vivino_linha(v) ORDER BY array_position(v_ids, v.id))
      FROM winecatalog.vinhos v WHERE v.id = ANY(v_ids)), '[]'));
END;
$$;

-- Uma linha por vinho tratado. Tira o vinho da fila e carimba a execução.
-- `sem_acao` quando não há nada a decidir: o link está certo e os números
-- que a página mostra são os que o catálogo já tem.
-- `p_revisao`: desde 25/09/2026 o script APLICA o que encontrou (pela
-- `aplicar_fontes`) e grava a verificação como 'aceite' (revista pelo
-- script); 'sem_acao' para o que não tem nada a decidir. Sem ele, o
-- comportamento de antes: pendente para o admin.
DROP FUNCTION IF EXISTS winecatalog.vivino_gravar(bigint, jsonb, text);
CREATE OR REPLACE FUNCTION winecatalog.vivino_gravar(
  p_vinho_id bigint, p_res jsonb, p_execucao text DEFAULT NULL, p_revisao text DEFAULT NULL
) RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE
  v       winecatalog.vinhos%ROWTYPE;
  v_prop  jsonb := p_res -> 'proposta';
  v_rev   text := 'pendente';
  v_id    bigint;
  v_fila  jsonb;
BEGIN
  IF COALESCE(auth.role(), '') <> 'service_role' THEN
    RAISE EXCEPTION 'Só o batch (service_role) chama isto.';
  END IF;
  SELECT * INTO v FROM winecatalog.vinhos WHERE id = p_vinho_id;
  IF v.id IS NULL THEN RAISE EXCEPTION 'Vinho % não existe.', p_vinho_id; END IF;

  IF p_res ->> 'estado' = 'certo'
     AND (v_prop IS NULL OR (
          winecatalog.igual(v.ficha -> 'vivino_url', v_prop -> 'vivino_url')
      AND (v_prop -> 'vivino_nota' IS NULL OR winecatalog.igual(v.ficha -> 'vivino_nota', v_prop -> 'vivino_nota'))
      AND (v_prop -> 'vivino_avaliacoes' IS NULL OR winecatalog.igual(v.ficha -> 'vivino_avaliacoes', v_prop -> 'vivino_avaliacoes'))))
  THEN
    v_rev := 'sem_acao';
  END IF;
  -- Bloqueado ou erro não é uma resposta sobre o vinho: não fica à espera
  -- de decisão, e o vinho volta a entrar numa próxima noite.
  IF p_res ->> 'estado' IN ('bloqueado','erro') THEN v_rev := 'sem_acao'; END IF;
  IF p_revisao IN ('aceite','sem_acao','pendente') AND p_res ->> 'estado' NOT IN ('bloqueado','erro') THEN
    v_rev := p_revisao;
  END IF;

  INSERT INTO winecatalog.vivino_verificacoes
    (vinho_id, execucao, url_antes, estado, nome_pagina, proposta, candidatos, detalhe, revisao,
     revisto_em, revisto_por)
  VALUES
    -- `url_antes` a null quer dizer "não havia link": o script grava o
    -- vinho ANTES de registar a verificação, e o COALESCE punha aqui o link
    -- novo como se fosse o de antes.
    (v.id, p_execucao, CASE WHEN p_res ? 'url_antes' THEN p_res ->> 'url_antes' ELSE v.ficha ->> 'vivino_url' END,
     p_res ->> 'estado',
     p_res ->> 'nome_pagina', v_prop, p_res -> 'candidatos', p_res -> 'detalhe', v_rev,
     CASE WHEN v_rev = 'aceite' THEN now() END,
     CASE WHEN v_rev = 'aceite' THEN 'script' END)
  RETURNING id INTO v_id;

  v_fila := COALESCE((SELECT valor::jsonb FROM winecatalog.config WHERE chave = 'vivino_fila'), '[]');
  IF p_res ->> 'estado' NOT IN ('bloqueado','erro') THEN
    SELECT COALESCE(jsonb_agg(value ORDER BY ord), '[]') INTO v_fila
      FROM jsonb_array_elements(v_fila) WITH ORDINALITY AS e(value, ord)
     WHERE value::text::bigint <> v.id;
  END IF;
  INSERT INTO winecatalog.config (chave, valor) VALUES
    ('vivino_fila', v_fila::text), ('vivino_ultima', now()::text)
  ON CONFLICT (chave) DO UPDATE SET valor = EXCLUDED.valor;
  RETURN v_id;
END;
$$;



CREATE OR REPLACE FUNCTION winecatalog.vivino_config()
  RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE
  v_fila jsonb;
BEGIN
  IF NOT winecatalog.sou_admin() THEN
    RAISE EXCEPTION 'Só o admin do catálogo vê isto.';
  END IF;
  v_fila := COALESCE((SELECT valor::jsonb FROM winecatalog.config WHERE chave = 'vivino_fila'), '[]');
  RETURN jsonb_build_object(
    'frequencia', COALESCE((SELECT valor FROM winecatalog.config WHERE chave = 'vivino_frequencia'), 'desligado'),
    'lote',       COALESCE((SELECT valor FROM winecatalog.config WHERE chave = 'vivino_lote')::int, 10),
    'ultima',     (SELECT valor FROM winecatalog.config WHERE chave = 'vivino_ultima'),
    'fila',       jsonb_array_length(v_fila),
    'pendentes',  (SELECT count(*) FROM winecatalog.vivino_verificacoes x WHERE x.revisao = 'pendente'
                    AND NOT EXISTS (SELECT 1 FROM winecatalog.alias a WHERE a.id_de = x.vinho_id)),
    'verificados',(SELECT count(DISTINCT vinho_id) FROM winecatalog.vivino_verificacoes),
    'total',      (SELECT count(*) FROM winecatalog.vinhos v
                    WHERE NOT EXISTS (SELECT 1 FROM winecatalog.alias a WHERE a.id_de = v.id))
  );
END;
$$;

CREATE OR REPLACE FUNCTION winecatalog.vivino_definir(p_frequencia text, p_lote integer)
  RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
BEGIN
  IF NOT winecatalog.sou_admin() THEN
    RAISE EXCEPTION 'Só o admin do catálogo mexe nisto.';
  END IF;
  IF p_frequencia NOT IN ('desligado','diario','dia_sim_dia_nao','semanal') THEN
    RAISE EXCEPTION 'Frequência desconhecida: %', p_frequencia;
  END IF;
  -- 30 é o teto: a 4–7 s por página (mais a procura quando o link está
  -- errado), um lote maior passa a ser tráfego que se nota.
  IF p_lote IS NULL OR p_lote < 1 OR p_lote > 30 THEN
    RAISE EXCEPTION 'O número de vinhos de cada vez vai de 1 a 30.';
  END IF;
  INSERT INTO winecatalog.config (chave, valor) VALUES
    ('vivino_frequencia', p_frequencia), ('vivino_lote', p_lote::text)
  ON CONFLICT (chave) DO UPDATE SET valor = EXCLUDED.valor;
  RETURN winecatalog.vivino_config();
END;
$$;

-- Pôr vinhos na fila da próxima execução (a ficha de um vinho, ou uma
-- lista à mão). Os que já lá estão não se repetem.
CREATE OR REPLACE FUNCTION winecatalog.vivino_pedir(p_ids bigint[])
  RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE
  v_fila jsonb;
BEGIN
  IF NOT winecatalog.sou_admin() THEN
    RAISE EXCEPTION 'Só o admin do catálogo mexe nisto.';
  END IF;
  v_fila := COALESCE((SELECT valor::jsonb FROM winecatalog.config WHERE chave = 'vivino_fila'), '[]');
  SELECT COALESCE(jsonb_agg(x ORDER BY ord), '[]') INTO v_fila FROM (
    SELECT x, min(ord) ord FROM (
      SELECT value::bigint x, ordinality ord FROM jsonb_array_elements_text(v_fila) WITH ORDINALITY
      UNION ALL
      SELECT i, 100000 + ordinality FROM unnest(p_ids) WITH ORDINALITY AS u(i, ordinality)
       WHERE EXISTS (SELECT 1 FROM winecatalog.vinhos v WHERE v.id = i)
    ) t GROUP BY x
  ) s;
  INSERT INTO winecatalog.config (chave, valor) VALUES ('vivino_fila', v_fila::text)
  ON CONFLICT (chave) DO UPDATE SET valor = EXCLUDED.valor;
  RETURN jsonb_build_object('fila', jsonb_array_length(v_fila));
END;
$$;

-- A lista do separador Alertas: cada verificação com o vinho e o que está
-- no catálogo AGORA (pode já ter mudado desde a noite em que se verificou).
CREATE OR REPLACE FUNCTION winecatalog.vivino_listar(p_revisao text DEFAULT 'pendente')
  RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
BEGIN
  IF NOT winecatalog.sou_admin() THEN
    RAISE EXCEPTION 'Só o admin do catálogo vê isto.';
  END IF;
  RETURN COALESCE((
    SELECT jsonb_agg(jsonb_build_object(
      'id', x.id, 'vinhoId', x.vinho_id, 'quando', x.verificado_em,
      'estado', x.estado, 'revisao', x.revisao, 'urlAntes', x.url_antes,
      'nomePagina', x.nome_pagina, 'proposta', x.proposta,
      'candidatos', x.candidatos, 'detalhe', x.detalhe,
      'revistoEm', x.revisto_em, 'revistoPor', x.revisto_por,
      'nome', v.nome, 'produtor', v.produtor, 'ano', v.ano,
      'tipo', v.ficha ->> 'tipo',
      'agora', jsonb_build_object(
        'vivino_url',        v.ficha -> 'vivino_url',
        'vivino_nota',       v.ficha -> 'vivino_nota',
        'vivino_avaliacoes', v.ficha -> 'vivino_avaliacoes'))
      ORDER BY x.verificado_em DESC, x.id DESC)
    FROM (
      -- Uma proposta por decidir de um vinho que entretanto foi FUNDIDO
      -- noutro já não é pergunta nenhuma: era para o nome antigo. Não
      -- aparece nos pendentes (a `vivino_resolver` também a recusa).
      SELECT * FROM winecatalog.vivino_verificacoes x0
       WHERE p_revisao = 'todos'
          OR (x0.revisao = p_revisao AND NOT (p_revisao = 'pendente' AND EXISTS (
                SELECT 1 FROM winecatalog.alias a WHERE a.id_de = x0.vinho_id)))
       ORDER BY verificado_em DESC, id DESC
       LIMIT 200
    ) x
    LEFT JOIN winecatalog.vinhos v ON v.id = x.vinho_id
  ), '[]'::jsonb);
END;
$$;

CREATE OR REPLACE FUNCTION winecatalog.vivino_contar()
  RETURNS integer LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
BEGIN
  IF NOT winecatalog.sou_admin() THEN RETURN 0; END IF;
  RETURN (SELECT count(*) FROM winecatalog.vivino_verificacoes x WHERE x.revisao = 'pendente'
            AND NOT EXISTS (SELECT 1 FROM winecatalog.alias a WHERE a.id_de = x.vinho_id));
END;
$$;

-- Decidir. `aceite` grava a proposta (ou `p_campos`, quando o admin escolhe
-- um dos candidatos em vez dela) pela `editar` — a mesma porta de qualquer
-- correção à mão, com a mesma força e o mesmo registo do antes e depois.
CREATE OR REPLACE FUNCTION winecatalog.vivino_resolver(
  p_id bigint, p_decisao text, p_campos jsonb DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
  SET search_path TO 'winecatalog', 'public'
AS $$
DECLARE
  r       winecatalog.vivino_verificacoes%ROWTYPE;
  v_alvo  bigint;
  v_campos jsonb;
  v_res   jsonb := NULL;
BEGIN
  IF NOT winecatalog.sou_admin() THEN
    RAISE EXCEPTION 'Só o admin do catálogo decide isto.';
  END IF;
  IF p_decisao NOT IN ('aceite','recusado','pendente') THEN
    RAISE EXCEPTION 'Decisão desconhecida: %', p_decisao;
  END IF;
  SELECT * INTO r FROM winecatalog.vivino_verificacoes WHERE id = p_id FOR UPDATE;
  IF r.id IS NULL THEN RAISE EXCEPTION 'Verificação não encontrada.'; END IF;

  IF p_decisao = 'aceite' THEN
    -- Só os três campos do Vivino, venha o que vier: isto não é uma porta
    -- para escrever outra coisa na ficha.
    SELECT COALESCE(jsonb_object_agg(key, value), '{}') INTO v_campos
      FROM jsonb_each(COALESCE(p_campos, r.proposta, '{}'))
     WHERE key IN ('vivino_url','vivino_nota','vivino_avaliacoes');
    IF v_campos = '{}'::jsonb THEN
      RAISE EXCEPTION 'Não há nada para aplicar nesta verificação.';
    END IF;
    -- Um vinho fundido DEPOIS de verificado: a proposta foi procurada pelo
    -- nome antigo, e aplicá-la ao vinho que ficou era pôr-lhe o link de
    -- outro (25/09/2026: o "Post" fundido no "Post Scriptum" tinha à espera
    -- o link de um "Post Reserve Cabernet Sauvignon" americano). Verifica-se
    -- outra vez o que ficou.
    SELECT id_para INTO v_alvo FROM winecatalog.alias WHERE id_de = r.vinho_id;
    IF v_alvo IS NOT NULL THEN
      RAISE EXCEPTION 'Este vinho foi fundido noutro (#%) depois de verificado — a proposta era para o nome antigo. Põe o que ficou na fila ("Verificar no Vivino").', v_alvo;
    END IF;
    v_res := winecatalog.editar(r.vinho_id, v_campos);
  END IF;

  UPDATE winecatalog.vivino_verificacoes
     SET revisao = p_decisao,
         revisto_em  = CASE WHEN p_decisao = 'pendente' THEN NULL ELSE now() END,
         revisto_por = CASE WHEN p_decisao = 'pendente' THEN NULL ELSE auth.email() END
   WHERE id = r.id;
  RETURN jsonb_build_object('ok', true, 'editar', v_res);
END;
$$;



-- ── Uma linha por chamada ao Gemini ────────────────────────────────────
-- Os TOKENS são facto — vêm do `usageMetadata` da API. O `custo_estimado_eur`
-- é uma ESTIMATIVA GROSSEIRA, calculada de constantes escritas à mão em
-- cada Edge Function, e a pesquisa Google é faturada à parte por pedido.
-- Não é um preço publicado, e não se deve ler como fatura.
--
-- `detalhe` guarda o payload inteiro do `sync_log` da app de origem: é o
-- que permite investigar um caso concreto sem ter de acrescentar uma
-- coluna por cada coisa nova que uma das cinco apps queira registar.
CREATE TABLE IF NOT EXISTS ia_uso.registos (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  criado_em          timestamptz NOT NULL DEFAULT now(),
  app                text NOT NULL,
  funcao             text NOT NULL,
  estado             text NOT NULL DEFAULT 'ok'
                       CHECK (estado IN ('pedido', 'ok', 'erro')),
  modelo             text,
  pesquisa_web       boolean,
  tokens_entrada     integer,
  tokens_saida       integer,
  tokens_pensamento  integer,
  tokens_total       integer,
  custo_estimado_eur numeric,
  duracao_ms         integer,
  quem               text,
  erro               text,
  detalhe            jsonb
);

-- Por data (o ecrã abre sempre pelo mais recente), por app+data (o filtro
-- que o painel usa) e por modelo (a pergunta "o flash-lite chega?").
CREATE INDEX IF NOT EXISTS registos_criado_idx
  ON ia_uso.registos USING btree (criado_em DESC);
CREATE INDEX IF NOT EXISTS registos_app_criado_idx
  ON ia_uso.registos USING btree (app, criado_em DESC);
CREATE INDEX IF NOT EXISTS registos_modelo_idx
  ON ia_uso.registos USING btree (modelo);


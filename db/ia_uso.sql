-- RLS, GRANTS e policies
-- ═══════════════════════════════════════════════════════════════════════
-- ISTO É O BLOCO QUE FALTOU CORRER À PRIMEIRA (20/09/2026) e sem o qual
-- NADA funciona: não havia um único GRANT no schema, nem sequer `USAGE`
-- para a `service_role`. Os INSERTs das 8 functions levavam 403 (42501) e
-- eram engolidos pelo `try/catch` delas — a tabela ficava a zero linhas
-- sem um erro em lado nenhum, e as funções de leitura estavam
-- inalcançáveis. Se algum dia isto voltar a estar vazio, é o primeiro
-- sítio a conferir (a seguir aos Exposed schemas, lá em cima).

ALTER TABLE ia_uso.registos ENABLE ROW LEVEL SECURITY;
ALTER TABLE ia_uso.config   ENABLE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA ia_uso TO anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA ia_uso TO service_role;
GRANT SELECT ON ia_uso.registos, ia_uso.config TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA ia_uso TO service_role;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA ia_uso TO authenticated, service_role;

ALTER DEFAULT PRIVILEGES IN SCHEMA ia_uso
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA ia_uso
  GRANT SELECT ON TABLES TO authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA ia_uso
  GRANT USAGE, SELECT ON SEQUENCES TO service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA ia_uso
  GRANT EXECUTE ON FUNCTIONS TO authenticated, service_role;

-- Segundo cinto: quem chegue às tabelas por REST (e não pelas funções) só
-- lê sendo admin. A `service_role` passa por cima do RLS, como é suposto —
-- é ela que escreve, de dentro das Edge Functions.
DROP POLICY IF EXISTS registos_admin_le ON ia_uso.registos;
CREATE POLICY registos_admin_le ON ia_uso.registos
  FOR SELECT TO authenticated USING (ia_uso.sou_admin());

DROP POLICY IF EXISTS config_admin_le ON ia_uso.config;
CREATE POLICY config_admin_le ON ia_uso.config
  FOR SELECT TO authenticated USING (ia_uso.sou_admin());


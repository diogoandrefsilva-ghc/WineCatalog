-- ═══════════════════════════════════════════════════════════════════════
-- ia_uso — o registo central de acessos ao Gemini
-- ═══════════════════════════════════════════════════════════════════════
-- Schema À PARTE, no MESMO projeto Supabase, partilhado pelas CINCO apps
-- que chamam o Gemini. Uma linha por chamada: quem, que app, que função,
-- que modelo, quantos tokens, quanto custou (estimado), quanto demorou e
-- o que correu mal.
--
-- PORQUE É QUE ISTO EXISTE. Cada app já tinha o seu `sync_log` e nenhuma
-- sabia o que as outras gastavam — a pergunta "quanto é que isto me está
-- a custar ao todo?" não tinha onde ser respondida. Somar cinco tabelas à
-- mão, em cinco schemas, com colunas diferentes, não é resposta.
--
-- PORQUE É UM SCHEMA À PARTE, e não uma tabela na WineCatalog. Pelo mesmo
-- motivo que o catálogo saiu da Garrafeira: isto não é de nenhuma das
-- cinco apps. Pendurá-lo numa delas era dar a quem herdasse essa app o
-- poder sobre uma tabela que regista o gasto de todas. Tem dono próprio
-- (`ia_uso.config.admin_email`), que não tem de ser o admin de nenhuma.
--
-- O QUE ESTE FICHEIRO NÃO DECIDE: o que cada app escreve aqui. Isso vive
-- na `registarIaUso()` de cada uma das 8 Edge Functions — duplicada de
-- propósito, como tudo neste projeto (cada Edge Function é auto-contida).
-- Ver "O registo central de acessos ao Gemini" no CLAUDE.md da WineCatalog.
--
-- ESCRITA: só a `service_role`, de dentro das Edge Functions
-- (`Content-Profile: ia_uso`). LEITURA: as funções `listar()`/`resumo()`,
-- com o portão `sou_admin()` lá dentro, mais as policies de SELECT como
-- segundo cinto para quem chegue à tabela por REST.
--
-- É IDEMPOTENTE: corre as vezes que forem precisas.
--
-- As 6 apps / 9 functions que escrevem aqui:
--   winecatalog    catalogo-info, catalogo-foto
--   garrafeira     vinho-info, importar-vinhos
--   wineselection  sugerir-vinho, verificar-vinhos
--   splitbill      fatura-restaurante
--   festasbv       fatura-ocr
--   goals          calendario-sporting
--
-- A `calendario-sporting` é a única que serve DUAS apps — o SplitBill lê o
-- mesmo calendário — e por isso grava `app` = quem chamou (`goals` ou
-- `splitbill`), não um "goals" fixo. A pergunta a que esta tabela existe
-- para responder é quanto custa cada APP, não quanto custa cada ficheiro.
--
-- PASSO MANUAL NO PAINEL: `ia_uso` tem de estar em Project Settings → API
-- → Data API → Exposed schemas. Sem isso o PostgREST responde PGRST106 e
-- os INSERTs das Edge Functions são engolidos pelo `try/catch` delas — a
-- tabela fica a zero sem um único erro à vista. É o pitfall do costume
-- com schemas não-`public`.
-- ═══════════════════════════════════════════════════════════════════════

CREATE SCHEMA IF NOT EXISTS ia_uso;

-- ── Quem manda aqui ────────────────────────────────────────────────────
-- Na BASE DE DADOS e não em código, como nas apps irmãs: a app nasce com
-- um dono e pode um dia passar para outro sem um deploy pelo meio.
CREATE TABLE IF NOT EXISTS ia_uso.config (
  chave text PRIMARY KEY,
  valor text NOT NULL
);


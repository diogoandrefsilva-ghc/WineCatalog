CREATE OR REPLACE FUNCTION ia_uso.sou_admin()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path TO 'ia_uso', 'public'
AS $$
  SELECT lower(COALESCE(auth.email(), '')) = ia_uso.admin_email();
$$;

-- Passar este painel a outra pessoa. Só o admin de agora o pode fazer.
CREATE OR REPLACE FUNCTION ia_uso.definir_admin(p_email text)
RETURNS text
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'ia_uso', 'public'
AS $$
DECLARE
  v_novo text := lower(trim(COALESCE(p_email, '')));
BEGIN
  IF NOT ia_uso.sou_admin() THEN
    RAISE EXCEPTION 'Só o admin pode passar este painel a outra pessoa.';
  END IF;
  IF v_novo = '' OR v_novo NOT LIKE '%@%' THEN
    RAISE EXCEPTION 'Email inválido.';
  END IF;
  INSERT INTO ia_uso.config (chave, valor) VALUES ('admin_email', v_novo)
  ON CONFLICT (chave) DO UPDATE SET valor = EXCLUDED.valor;
  RETURN 'ok';
END;
$$;

-- Os registos em bruto, do mais recente para o mais antigo. O limite é
-- capado a 1000 — é um painel, não um export.
CREATE OR REPLACE FUNCTION ia_uso.listar(
  p_limite integer DEFAULT 200,
  p_app text DEFAULT NULL,
  p_desde timestamptz DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path TO 'ia_uso', 'public'
AS $$
BEGIN
  IF NOT ia_uso.sou_admin() THEN
    RAISE EXCEPTION 'Só o admin vê os acessos à IA.';
  END IF;
  RETURN COALESCE((
    SELECT jsonb_agg(to_jsonb(r) ORDER BY r.criado_em DESC)
    FROM (
      SELECT * FROM ia_uso.registos
       WHERE (p_app IS NULL OR app = p_app)
         AND (p_desde IS NULL OR criado_em >= p_desde)
       ORDER BY criado_em DESC
       LIMIT LEAST(GREATEST(COALESCE(p_limite, 200), 1), 1000)
    ) r
  ), '[]'::jsonb);
END;
$$;

-- Os totais: por app, por modelo, na janela pedida e desde sempre.
-- `porApp`/`porModelo` são do TOTAL acumulado (não da janela) de propósito
-- — a pergunta "quanto é que cada app já gastou" não se responde com 30
-- dias; a janela serve para ver o ritmo de agora, e vem à parte.
CREATE OR REPLACE FUNCTION ia_uso.resumo(p_dias integer DEFAULT 30)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path TO 'ia_uso', 'public'
AS $$
DECLARE
  v_desde timestamptz := now() - make_interval(days => GREATEST(COALESCE(p_dias, 30), 1));
BEGIN
  IF NOT ia_uso.sou_admin() THEN
    RAISE EXCEPTION 'Só o admin vê os acessos à IA.';
  END IF;
  RETURN jsonb_build_object(
    'janelaDias', p_dias,
    'porApp', COALESCE((
      SELECT jsonb_agg(x ORDER BY (x ->> 'pedidos')::int DESC) FROM (
        SELECT jsonb_build_object(
          'app', app,
          'pedidos', count(*),
          'ok', count(*) FILTER (WHERE estado = 'ok'),
          'erro', count(*) FILTER (WHERE estado = 'erro'),
          'tokensEntrada', COALESCE(sum(tokens_entrada), 0),
          'tokensSaida', COALESCE(sum(tokens_saida), 0),
          'custoEur', COALESCE(sum(custo_estimado_eur), 0),
          'ultimaChamada', max(criado_em)
        ) AS x
        FROM ia_uso.registos GROUP BY app
      ) t
    ), '[]'::jsonb),
    'porModelo', COALESCE((
      SELECT jsonb_agg(x ORDER BY (x ->> 'pedidos')::int DESC) FROM (
        SELECT jsonb_build_object(
          'modelo', COALESCE(modelo, '(desconhecido)'),
          'pedidos', count(*),
          'tokensEntrada', COALESCE(sum(tokens_entrada), 0),
          'tokensSaida', COALESCE(sum(tokens_saida), 0),
          'custoEur', COALESCE(sum(custo_estimado_eur), 0)
        ) AS x
        FROM ia_uso.registos GROUP BY modelo
      ) t
    ), '[]'::jsonb),
    'janela', (
      SELECT jsonb_build_object(
        'pedidos', count(*),
        'tokensEntrada', COALESCE(sum(tokens_entrada), 0),
        'tokensSaida', COALESCE(sum(tokens_saida), 0),
        'custoEur', COALESCE(sum(custo_estimado_eur), 0)
      ) FROM ia_uso.registos WHERE criado_em >= v_desde
    ),
    'total', (
      SELECT jsonb_build_object(
        'pedidos', count(*),
        'tokensEntrada', COALESCE(sum(tokens_entrada), 0),
        'tokensSaida', COALESCE(sum(tokens_saida), 0),
        'custoEur', COALESCE(sum(custo_estimado_eur), 0)
      ) FROM ia_uso.registos
    )
  );
END;
$$;


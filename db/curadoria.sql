GRANT EXECUTE ON FUNCTION winecatalog.comparar(text, text, integer, jsonb) TO authenticated;
GRANT EXECUTE ON FUNCTION winecatalog.reportar(text, text, integer, text, jsonb, text, text) TO authenticated;
